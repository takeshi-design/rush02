#include "ft_printf.h"
#include <stdio.h>

int	main()
{
	const char	*str = "hello world %c%s%p%k%";
	const char	*s = "aaa";
	const char	*ar = "\0";

	ft_printf(str, '!', s);
	printf("\n");
	printf(str, '!', s);
	printf("\n");
	ft_printf("%s a\n", ar);
	printf("%s a\n", ar);
	write(1, "c\n", 2);
	close(1);
	dprintf(2, "%d\n", ft_printf("c"));
	dprintf(2, "%d\n", printf("c"));
	return (0);
}


//コンパイル
//ccw main.c -I. -L. -lftprintf -o main -no-pie


//2. 標準の printf("c") が 1 を返した理由

//ここが一番不思議に思うポイントですが、標準の printf はバッファリング（一時保存）という仕組みを使っているため、このような結果になります。
//1. バッファへの書き込みは成功する: printf("c") が呼ばれたとき、文字 "c" は画面（ファイル記述子 1）に直接送られるのではなく、まずメモリ上の「バッファ」に溜められます。メモリへの書き込み自体は成功するため、printf はこの時点で「1文字の書き込み（準備）に成功した」と判断し、1 を返します。
//2. 実際の出力（フラッシュ）は後で行われる: バッファに溜まった文字が実際にファイル記述子 1 へ書き込まれる（フラッシュされる）のは、改行 \n が来たときや、プログラムが終了するときです。
//3. エラーは後から発生する: プログラム終了時などにいざファイル記述子 1 へ書き込もうとした瞬間、初めて close(1) の影響でエラーが発生しますが、すでに printf は実行を終えて 1 を返してしまっているため、戻り値にはエラーが反映されません。
